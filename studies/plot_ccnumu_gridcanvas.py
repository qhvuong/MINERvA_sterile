def open_root(path):
    f = ROOT.TFile.Open(path)

    if not f or f.IsZombie():
        raise RuntimeError(f"Cannot open ROOT file: {path}")

    return f


def read_pot(f):
    meta = f.Get("Meta")

    if not meta or not meta.InheritsFrom("TTree"):
        return None

    if not meta.GetBranch("POT_Used"):
        return None

    pot = sum(float(entry.POT_Used) for entry in meta)

    if not math.isfinite(pot) or pot <= 0:
        return None

    return pot


def get_cv(f, histname, newname):
    obj = f.Get(histname)

    if not obj or not obj.InheritsFrom("TH2"):
        raise RuntimeError(
            f"Missing TH2 histogram '{histname}' "
            f"in file {f.GetName()}"
        )

    if hasattr(obj, "GetCVHistoWithStatError"):
        h = obj.GetCVHistoWithStatError()
    else:
        h = obj.Clone(newname)

    h.SetName(newname)
    h.SetDirectory(0)

    return h


def get_edges(axis):
    return [
        axis.GetBinLowEdge(i)
        for i in range(1, axis.GetNbins() + 2)
    ]


def validate_binning(data, mc, config):
    """Verify both axes and Data/MC consistency."""

    if (
        data.GetNbinsX() != config["expected_xbins"]
        or data.GetNbinsY() != config["expected_ybins"]
    ):
        raise RuntimeError(
            f"Unexpected binning for {config['hist']}: "
            f"X={data.GetNbinsX()}, Y={data.GetNbinsY()}. "
            f"Expected X={config['expected_xbins']}, "
            f"Y={config['expected_ybins']}. "
            "Regenerate the ROOT histograms using "
            "the updated plot configuration."
        )

    for axis_name in ("X", "Y"):
        data_axis = getattr(data, f"Get{axis_name}axis")()
        mc_axis = getattr(mc, f"Get{axis_name}axis")()

        data_edges = get_edges(data_axis)
        mc_edges = get_edges(mc_axis)

        if len(data_edges) != len(mc_edges):
            raise RuntimeError(
                f"Data/MC {axis_name} bin counts differ"
            )

        for d, m in zip(data_edges, mc_edges):
            if not math.isclose(d, m, rel_tol=1e-8, abs_tol=1e-8):
                raise RuntimeError(
                    f"Data/MC {axis_name} bin edges differ: "
                    f"{d} versus {m}"
                )


def projection_x(h2, slice_bin, name):
    """
    Project X for exactly one Y bin.

    X: fine plotted variable
    Y: coarse slicing variable
    """

    h = h2.ProjectionX(
        name,
        slice_bin,
        slice_bin,
        "e",
    )

    h.SetDirectory(0)
    h.SetTitle("")
    h.GetXaxis().SetTitle("")
    h.GetYaxis().SetTitle("")

    return h


# ============================================================
# DATA/MC RATIO
# ============================================================

def make_ratio(data, mc, name, combined_stat=False):
    ratio = data.Clone(name)
    ratio.SetDirectory(0)
    ratio.Reset("ICES")

    points = []

    for i in range(1, data.GetNbinsX() + 1):
        d = data.GetBinContent(i)
        m = mc.GetBinContent(i)

        if not math.isfinite(d) or not math.isfinite(m) or m <= 0:
            continue

        de = data.GetBinError(i)
        me = mc.GetBinError(i)

        value = d / m
        variance = (de / m) ** 2

        if combined_stat:
            variance += (d * me / (m * m)) ** 2

        error = math.sqrt(max(variance, 0.0))

        ratio.SetBinContent(i, value)
        ratio.SetBinError(i, error)

        points.append((
            ratio.GetXaxis().GetBinCenter(i),
            value,
            error,
        ))

    graph = ROOT.TGraphErrors(len(points))
    graph.SetName(name + "_graph")

    for j, (x, y, error) in enumerate(points):
        graph.SetPoint(j, x, y)
        graph.SetPointError(j, 0.0, error)

    graph.SetMarkerStyle(20)
    graph.SetMarkerSize(0.65)
    graph.SetMarkerColor(ROOT.kBlack)
    graph.SetLineColor(ROOT.kBlack)
    graph.SetLineWidth(1)

    return ratio, graph


def make_mc_ratio_band(mc, name):
    """MC statistical uncertainty centered at Data/MC = 1."""

    points = []

    for i in range(1, mc.GetNbinsX() + 1):
        m = mc.GetBinContent(i)

        if not math.isfinite(m) or m <= 0:
            continue

        me = mc.GetBinError(i)

        x = mc.GetXaxis().GetBinCenter(i)
        ex = 0.5 * mc.GetXaxis().GetBinWidth(i)
        ey = me / m

        points.append((x, 1.0, ex, ey))

    band = ROOT.TGraphErrors(len(points))
    band.SetName(name)

    for j, (x, y, ex, ey) in enumerate(points):
        band.SetPoint(j, x, y)
        band.SetPointError(j, ex, ey)

    band.SetFillColor(ROOT.kGray + 1)
    band.SetFillStyle(3001)
    band.SetLineColor(ROOT.kGray + 2)
    band.SetLineWidth(1)

    return band


# ============================================================
# GRIDCANVAS
# ============================================================

def make_grid(
    data2d,
    mc2d,
    slice_label,
    horizontal_label,
    output,
    ymin=0.4,
    ymax=1.6,
    combined_stat=False,
):
    """
    Both histograms have:

        X = fine plotted variable
        Y = coarse slice variable

    Each panel is a ProjectionX over one Y bin.
    """

    slice_axis = data2d.GetYaxis()
    n_slices = slice_axis.GetNbins()

    ncols = min(4, n_slices)
    nrows = math.ceil(n_slices / ncols)

    gc = PlotUtils.GridCanvas(
        "gc_" + os.path.basename(output),
        ncols,
        nrows,
        1400,
        max(700, 260 * nrows),
    )

    gc.SetLeftMargin(0.12)
    gc.SetRightMargin(0.02)
    gc.ResetPads()

    keep = []

    for ibin in range(1, n_slices + 1):
        pad = gc.cd(ibin)

        pad.SetFillColor(ROOT.kWhite)
        pad.SetTicks(1, 1)

        # --------------------------------------------
        # Project fine X distribution in coarse Y slice
        # --------------------------------------------

        h_data = projection_x(
            data2d,
            ibin,
            f"data_proj_{os.path.basename(output)}_{ibin}",
        )

        h_mc = projection_x(
            mc2d,
            ibin,
            f"mc_proj_{os.path.basename(output)}_{ibin}",
        )

        ratio, graph = make_ratio(
            h_data,
            h_mc,
            f"ratio_{os.path.basename(output)}_{ibin}",
            combined_stat,
        )

        band = make_mc_ratio_band(
            h_mc,
            f"mc_band_{os.path.basename(output)}_{ibin}",
        )

        # --------------------------------------------
        # Axes
        # --------------------------------------------

        ratio.SetTitle("")
        ratio.GetXaxis().SetTitle("")
        ratio.GetYaxis().SetTitle("")

        ratio.SetMinimum(ymin)
        ratio.SetMaximum(ymax)
        ratio.SetLineColor(ROOT.kWhite)
        ratio.SetMarkerSize(0)

        col = (ibin - 1) % ncols

        # Bottommost occupied pad of each column
        is_bottom = (ibin + ncols > n_slices)

        # Leftmost column
        is_left = (col == 0)

        ratio.GetXaxis().SetLabelSize(
            0.022 if is_bottom else 0.0
        )
        ratio.GetYaxis().SetLabelSize(
            0.022 if is_left else 0.0
        )

        ratio.GetXaxis().SetTickLength(0.02)
        ratio.GetYaxis().SetTickLength(0.02)

        ratio.GetXaxis().SetNdivisions(505)
        ratio.GetYaxis().SetNdivisions(505)

        ratio.Draw("HIST")

        # --------------------------------------------
        # MC statistical uncertainty
        # --------------------------------------------

        band.Draw("E2 SAME")

        # --------------------------------------------
        # Unity reference
        # --------------------------------------------

        xmin = ratio.GetXaxis().GetXmin()
        xmax = ratio.GetXaxis().GetXmax()

        unity = ROOT.TLine(xmin, 1.0, xmax, 1.0)
        unity.SetLineColor(ROOT.kRed + 1)
        unity.SetLineWidth(2)
        unity.SetLineStyle(1)
        unity.Draw("SAME")

        # --------------------------------------------
        # Data/MC ratio points
        # --------------------------------------------

        graph.Draw("P SAME")

        # --------------------------------------------
        # Slice labels
        # --------------------------------------------

        low = slice_axis.GetBinLowEdge(ibin)
        high = slice_axis.GetBinUpEdge(ibin)

        label_text = (
            f"{low:.2f} < {slice_label} < {high:.2f}"
        )

        pad.cd()

        label = ROOT.TLatex(
            1.0 - pad.GetRightMargin() - 0.01,
            1.0 - pad.GetTopMargin() - 0.01,
            label_text,
        )

        label.SetNDC()
        label.SetTextFont(42)
        label.SetTextAlign(33)

        if nrows == 1:
            text_size = 0.03
        elif ncols < nrows:
            text_size = 28.0 / (150.0 * nrows)
        elif ncols == nrows:
            text_size = 10.0 / (150.0 * ncols)
        else:
            text_size = 18.0 / (150.0 * ncols)

        label.SetTextSize(text_size)
        label.Draw()

        pad.RedrawAxis()

        keep.extend([
            h_data,
            h_mc,
            ratio,
            graph,
            band,
            unity,
            label,
        ])

    # --------------------------------------------
    # Shared axes
    # --------------------------------------------

    gc.cd()

    gc.SetXTitle(horizontal_label)
    gc.SetYTitle("Data / MC")
    gc.SetYLimits(ymin, ymax)
    gc.SetTitleSize(20.0)

    gc.Modified()
    gc.Update()

    gc.Print(output + "Maria_p6.png")
    gc.Print(output + "Maria_p6.pdf")

    print(f"Saved: {output}.png")

    return gc, keep


# ============================================================
# MAIN
# ============================================================

def main():
    parser = argparse.ArgumentParser()

    parser.add_argument("--data", default=DATA_FILE)
    parser.add_argument("--mc", default=MC_FILE)

    parser.add_argument(
        "--only",
        choices=["both", "pt", "ppar"],
        default="both",
        help="Choose which distribution to plot.",
    )

    parser.add_argument(
        "--outdir",
        default="/exp/minerva/data/users/qvuong/studies/ccnumu_v1_gridcanvas",
    )

    parser.add_argument("--scale", type=float, default=None)
    parser.add_argument("--ratio-min", type=float, default=0.4)
    parser.add_argument("--ratio-max", type=float, default=1.6)

    parser.add_argument(
        "--combined-stat",
        action="store_true",
        help="Include MC statistical uncertainty in point errors.",
    )

    args = parser.parse_args()

    if args.ratio_min >= args.ratio_max:
        parser.error("Ratio minimum must be below maximum")

    set_style()

    f_data = open_root(args.data)
    f_mc = open_root(args.mc)

    data_pot = read_pot(f_data)
    mc_pot = read_pot(f_mc)

    if args.scale is not None:
        scale = args.scale
    elif data_pot is not None and mc_pot is not None:
        scale = data_pot / mc_pot
    else:
        raise RuntimeError(
            "Unable to determine POT scaling. Use --scale."
        )

    if not math.isfinite(scale) or scale <= 0:
        raise RuntimeError("Invalid MC scaling factor")

    print("\n========== POT NORMALIZATION ==========")
    print("Data POT:", data_pot)
    print("MC POT:", mc_pot)
    print("MC scale:", scale)
    print("=======================================\n")

    os.makedirs(args.outdir, exist_ok=True)

    if args.only == "both":
        selected = ["pt", "ppar"]
    else:
        selected = [args.only]

    keep_alive = []

    for key in selected:
        config = HIST_CONFIGS[key]
        histname = config["hist"]

        data = get_cv(
            f_data,
            histname,
            f"data_2d_{key}",
        )

        mc = get_cv(
            f_mc,
            histname,
            f"mc_2d_{key}",
        )

        validate_binning(data, mc, config)

        mc.Scale(scale)

        print(f"\n========== {histname} ==========")
        print("X bins:", data.GetNbinsX())
        print("Y bins:", data.GetNbinsY())
        print("Data events:", data.Integral())
        print("Scaled MC events:", mc.Integral())
        print("X edges:", get_edges(data.GetXaxis()))
        print("Y edges:", get_edges(data.GetYaxis()))
        print("================================\n")

        output = os.path.join(
            args.outdir,
            config["name"],
        )

        result = make_grid(
            data,
            mc,
            config["slice_label"],
            config["horizontal_label"],
            output,
            ymin=args.ratio_min,
            ymax=args.ratio_max,
            combined_stat=args.combined_stat,
        )

        keep_alive.append((data, mc, result))

    f_data.Close()
    f_mc.Close()


if __name__ == "__main__":
    main()
