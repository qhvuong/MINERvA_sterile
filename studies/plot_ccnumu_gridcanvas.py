def set_style():
    s = ROOT.gStyle

    s.SetOptStat(0)
    s.SetOptTitle(0)
    s.SetOptFit(0)

    s.SetPadTopMargin(0.05)
    s.SetPadRightMargin(0.02)
    s.SetPadBottomMargin(0.12)
    s.SetPadLeftMargin(0.10)

    s.SetLabelFont(42, "XYZ")
    s.SetTitleFont(42, "XYZ")

    s.SetLabelSize(0.022, "X")
    s.SetLabelSize(0.022, "Y")

    s.SetTitleSize(0.035, "X")
    s.SetTitleSize(0.035, "Y")

    s.SetEndErrorSize(2)
    s.SetErrorX(0)

    s.SetNdivisions(505, "X")
    s.SetNdivisions(505, "Y")


