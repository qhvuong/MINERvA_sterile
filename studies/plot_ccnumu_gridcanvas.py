"""
CCnumu reconstructed Data/MC ratio panels using MINERvA GridCanvas.

Uses TWO independent 2D histograms:

1. Lepton_Pt_Ppar
   X = fine muon pT bins
   Y = coarse muon p_parallel bins
   -> plot pT distributions in p_parallel slices

2. Lepton_Ppar_Pt
   X = fine muon p_parallel bins
   Y = coarse muon pT bins
   -> plot p_parallel distributions in pT slices

Features:
  - Native PlotUtils.GridCanvas
  - Original histogram binning (no rebinning)
  - POT normalization
  - Data statistical error bars
  - MC statistical uncertainty band around unity
  - Red unity reference line
  - Both distributions generated by default
"""

