def open_root(path):
    f = ROOT.TFile.Open(path)

    if not f or f.IsZombie():
        raise RuntimeError(
            f"Cannot open ROOT file: {path}"
        )

    return f


def read_pot(f):
    meta = f.Get("Meta")

    if not meta or not meta.InheritsFrom("TTree"):
        return None

    if not meta.GetBranch("POT_Used"):
        return None

    pot = sum(
        float(entry.POT_Used)
        for entry in meta
    )

    if not math.isfinite(pot) or pot <= 0:
        return None

    return pot


def get_cv(f, histname, newname, required=True):
    obj = f.Get(histname)

    if not obj or not obj.InheritsFrom("TH2"):
        if required:
            raise RuntimeError(
                f"Missing TH2 histogram '{histname}' "
                f"in file {f.GetName()}"
            )
        return None

    if hasattr(obj, "GetCVHistoWithStatError"):
        h = obj.GetCVHistoWithStatError()
    else:
        h = obj.Clone(newname)

    h.SetName(newname)
    h.SetDirectory(0)

    return h


def get_edges(axis):
    return [
        axis.GetBinLowEdge(i)
        for i in range(1, axis.GetNbins() + 2)
    ]


def validate_binning(data, mc, config):
    if (
        data.GetNbinsX() != config["expected_xbins"]
        or data.GetNbinsY() != config["expected_ybins"]
    ):
        raise RuntimeError(
            f"Unexpected binning for {config['hist']}: "
            f"X={data.GetNbinsX()}, Y={data.GetNbinsY()}. "
            f"Expected X={config['expected_xbins']}, "
            f"Y={config['expected_ybins']}."
        )

    validate_matching_axes(data, mc)


def validate_matching_axes(reference, candidate):
    for axis_name in ("X", "Y"):
        a = getattr(reference, f"Get{axis_name}axis")()
        b = getattr(candidate, f"Get{axis_name}axis")()

        edges_a = get_edges(a)
        edges_b = get_edges(b)

        if len(edges_a) != len(edges_b):
            raise RuntimeError(
                f"Different {axis_name} bin counts: "
                f"{reference.GetName()} vs {candidate.GetName()}"
            )

        for x, y in zip(edges_a, edges_b):
            if not math.isclose(
                x, y, rel_tol=1e-8, abs_tol=1e-8
            ):
                raise RuntimeError(
                    f"Different {axis_name} bin edges: "
                    f"{reference.GetName()} vs {candidate.GetName()}"
                )


def projection_x(h2, slice_bin, name):
    h = h2.ProjectionX(
        name,
        slice_bin,
        slice_bin,
        "e",
    )

    h.SetDirectory(0)
    h.SetTitle("")
    h.GetXaxis().SetTitle("")
    h.GetYaxis().SetTitle("")

    return h


