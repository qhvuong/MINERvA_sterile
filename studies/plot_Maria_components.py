def load_components(f_mc, histname, nominal_mc, scale):
    """
    Load truth-category histograms.

    Each component is POT-scaled identically to nominal MC.
    Only the categories actually present are included.

    Returns:
        components: list of (label, TH2, color)
        missing: missing histogram names
    """

    components = []
    missing = []
    found_count = 0

    for label, suffixes, color in COMPONENTS:

        combined = None

        for suffix in suffixes:
            name = f"{histname}_{suffix}"

            h = get_cv(
                f_mc,
                name,
                f"component_{histname}_{suffix}",
                required=False,
            )

            if h is None:
                missing.append(name)
                continue

            validate_matching_axes(nominal_mc, h)

            # Apply identical POT normalization.
            h.Scale(scale)

            print(
                f"[COMPONENT FOUND] {name}: "
                f"integral={h.Integral():.6g}"
            )

            found_count += 1

            if combined is None:
                combined = h
            else:
                combined.Add(h)

        if combined is not None:
            components.append(
                (label, combined, color)
            )

    if found_count == 0:
        raise RuntimeError(
            f"No component histograms found for {histname}. "
            "The inclusive histogram alone cannot provide "
            "the MC interaction breakdown. "
            "Check the ROOT histogram names or regenerate "
            "the truth-category histograms."
        )

    if missing:
        print("\n[WARNING] Missing component histograms:")
        for name in missing:
            print("  ", name)

    return components, missing


