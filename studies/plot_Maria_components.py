# DATA / MC RATIO
# ============================================================

def make_ratio(
    data,
    mc,
    name,
    combined_stat=False,
):
    ratio = data.Clone(name)
    ratio.SetDirectory(0)
    ratio.Reset("ICES")

    points = []

    for i in range(1, data.GetNbinsX() + 1):
        d = data.GetBinContent(i)
        m = mc.GetBinContent(i)

        if (
            not math.isfinite(d)
            or not math.isfinite(m)
            or m <= 0
        ):
            continue

        de = data.GetBinError(i)
        me = mc.GetBinError(i)

        value = d / m
        variance = (de / m) ** 2

        if combined_stat:
            variance += (
                d * me / (m * m)
            ) ** 2

        error = math.sqrt(
            max(variance, 0.0)
        )

        ratio.SetBinContent(i, value)
        ratio.SetBinError(i, error)

        points.append((
            ratio.GetXaxis().GetBinCenter(i),
            value,
            error,
        ))

    graph = ROOT.TGraphErrors(
        len(points)
    )

    graph.SetName(
        name + "_graph"
    )

    for j, (x, y, error) in enumerate(points):
        graph.SetPoint(j, x, y)
        graph.SetPointError(
            j, 0.0, error
        )

    graph.SetMarkerStyle(20)
    graph.SetMarkerSize(0.65)
    graph.SetMarkerColor(ROOT.kBlack)
    graph.SetLineColor(ROOT.kBlack)
    graph.SetLineWidth(1)

    return ratio, graph


# ============================================================
# MC STATISTICAL UNCERTAINTY BAND
# ============================================================

def make_mc_ratio_band(mc, name):
    points = []

    for i in range(1, mc.GetNbinsX() + 1):
        m = mc.GetBinContent(i)

        if not math.isfinite(m) or m <= 0:
            continue

        me = mc.GetBinError(i)

        x = mc.GetXaxis().GetBinCenter(i)
        ex = 0.5 * mc.GetXaxis().GetBinWidth(i)
        ey = me / m

        points.append((x, 1.0, ex, ey))

    band = ROOT.TGraphErrors(
        len(points)
    )

    band.SetName(name)

    for j, (x, y, ex, ey) in enumerate(points):
        band.SetPoint(j, x, y)
        band.SetPointError(j, ex, ey)

    band.SetFillColor(ROOT.kGray)
    band.SetFillStyle(3001)
    band.SetLineColor(ROOT.kGray + 1)
    band.SetLineWidth(1)

    return band


# ============================================================
# MC COMPONENT / TOTAL NOMINAL MC
# ============================================================

def make_component_fraction(
    component,
    nominal,
    name,
    color,
):
    """
    Construct:

        R_component = MC_component / MC_total

    Both inputs are already POT scaled.

    No error bars are drawn for individual components.
    """

    fraction = component.Clone(name)
    fraction.SetDirectory(0)
    fraction.Reset("ICES")

    for i in range(1, nominal.GetNbinsX() + 1):
        total = nominal.GetBinContent(i)
        value = component.GetBinContent(i)

        if (
            not math.isfinite(total)
            or not math.isfinite(value)
            or total <= 0
        ):
            continue

        fraction.SetBinContent(
            i,
            value / total,
        )

        fraction.SetBinError(i, 0.0)

    fraction.SetLineColor(color)
    fraction.SetLineWidth(2)
    fraction.SetLineStyle(1)
    fraction.SetFillStyle(0)
    fraction.SetMarkerSize(0)

    return fraction


