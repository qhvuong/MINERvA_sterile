def main():

    parser = argparse.ArgumentParser()

    parser.add_argument(
        "--data",
        default=DATA_FILE,
    )

    parser.add_argument(
        "--mc",
        default=MC_FILE,
    )

    parser.add_argument(
        "--only",
        choices=["both", "pt", "ppar"],
        default="both",
    )

    parser.add_argument(
        "--outdir",
        default=(
            "/exp/minerva/data/users/qvuong/"
            "studies/ccnumu_v1_gridcanvas"
        ),
    )

    parser.add_argument(
        "--scale",
        type=float,
        default=None,
        help="Override automatic Data POT / MC POT",
    )

    parser.add_argument(
        "--combined-stat",
        action="store_true",
        help="Include MC statistical uncertainty in Data/MC point errors",
    )

    args = parser.parse_args()

    set_style()

    f_data = open_root(args.data)
    f_mc = open_root(args.mc)

    try:

        data_pot = read_pot(f_data)
        mc_pot = read_pot(f_mc)

        if args.scale is not None:
            scale = args.scale
        elif data_pot is not None and mc_pot is not None:
            scale = data_pot / mc_pot
        else:
            raise RuntimeError(
                "Unable to determine POT scaling. "
                "Use --scale."
            )

        if not math.isfinite(scale) or scale <= 0:
            raise RuntimeError(
                "Invalid MC scaling factor"
            )

        print("\n========== POT NORMALIZATION ==========")
        print("Data POT:", data_pot)
        print("MC POT:", mc_pot)
        print("MC scale:", scale)
        print("=======================================\n")

        os.makedirs(
            args.outdir,
            exist_ok=True,
        )

        selected = (
            ["pt", "ppar"]
            if args.only == "both"
            else [args.only]
        )

        keep_alive = []

        for key in selected:

            config = HIST_CONFIGS[key]
            histname = config["hist"]

            # --------------------------------------------
            # Inclusive Data and nominal MC
            # --------------------------------------------

            data = get_cv(
                f_data,
                histname,
                f"data_2d_{key}",
            )

            mc = get_cv(
                f_mc,
                histname,
                f"mc_2d_{key}",
            )

            validate_binning(
                data,
                mc,
                config,
            )

            # POT scale the nominal MC.
            mc.Scale(scale)

            # --------------------------------------------
            # Truth component histograms
            # --------------------------------------------

            components, missing = load_components(
                f_mc,
                histname,
                mc,
                scale,
            )

            print(f"\n========== {histname} ==========")
            print("X bins:", data.GetNbinsX())
            print("Y bins:", data.GetNbinsY())
            print("Data events:", data.Integral())
            print("Scaled MC events:", mc.Integral())

            print(
                "X edges:",
                get_edges(data.GetXaxis()),
            )

            print(
                "Y edges:",
                get_edges(data.GetYaxis()),
            )

            print("================================\n")

            output = os.path.join(
                args.outdir,
                config["name"] + "_components_MariasCuts_v1_fixedMuonAngle_LE1_p8",
            )

            # --------------------------------------------
            # Draw ratio grid with components
            # --------------------------------------------

            result = make_grid(
                data,
                mc,
                components,
                config["slice_label"],
                config["horizontal_label"],
                output,
                ymin=0.0,
                ymax=2.0,
                combined_stat=args.combined_stat,
            )

            keep_alive.append(
                (data, mc, components, result)
            )

    finally:
        f_data.Close()
        f_mc.Close()


if __name__ == "__main__":
    main()
