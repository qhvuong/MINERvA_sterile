def make_grid(
    data2d,
    mc2d,
    components2d,
    slice_label,
    horizontal_label,
    output,
    ymin=0.0,
    ymax=2.0,
    combined_stat=False,
):
    """
    Plot Data/MC and MC component fractions in each slice.

    All curves share the same total nominal MC denominator.
    """

    slice_axis = data2d.GetYaxis()
    n_slices = slice_axis.GetNbins()

    ncols = min(4, n_slices)
    nrows = math.ceil(n_slices / ncols)

    gc = PlotUtils.GridCanvas(
        "gc_" + os.path.basename(output),
        ncols,
        nrows,
        1400,
        max(700, 260 * nrows),
    )

    gc.SetLeftMargin(0.12)
    gc.SetRightMargin(0.02)
    gc.SetBottomMargin(0.14)
    gc.ResetPads()

    keep = []
    drawn_component_labels = set()
    residual_drawn = False

    # --------------------------------------------------------
    # Draw all momentum slices
    # --------------------------------------------------------

    for ibin in range(1, n_slices + 1):

        pad = gc.cd(ibin)

        pad.SetFillColor(ROOT.kWhite)
        pad.SetTicks(1, 1)

        h_data = projection_x(
            data2d,
            ibin,
            f"data_proj_{os.path.basename(output)}_{ibin}",
        )

        h_mc = projection_x(
            mc2d,
            ibin,
            f"mc_proj_{os.path.basename(output)}_{ibin}",
        )

        ratio, graph = make_ratio(
            h_data,
            h_mc,
            f"ratio_{os.path.basename(output)}_{ibin}",
            combined_stat,
        )

        band = make_mc_ratio_band(
            h_mc,
            f"mc_band_{os.path.basename(output)}_{ibin}",
        )

        # ----------------------------------------------------
        # Axes
        # ----------------------------------------------------

        ratio.SetTitle("")
        ratio.GetXaxis().SetTitle("")
        ratio.GetYaxis().SetTitle("")

        ratio.SetMinimum(ymin)
        ratio.SetMaximum(ymax)

        ratio.SetLineColor(ROOT.kWhite)
        ratio.SetMarkerSize(0)

        col = (ibin - 1) % ncols

        is_bottom = (
            ibin + ncols > n_slices
        )

        is_left = (
            col == 0
        )

        ratio.GetXaxis().SetLabelSize(
            0.022 if is_bottom else 0.0
        )

        ratio.GetYaxis().SetLabelSize(
            0.022 if is_left else 0.0
        )

        ratio.GetXaxis().SetTickLength(0.02)
        ratio.GetYaxis().SetTickLength(0.02)

        ratio.GetXaxis().SetNdivisions(505)
        ratio.GetYaxis().SetNdivisions(505)

        ratio.Draw("HIST")

        # ----------------------------------------------------
        # MC statistical uncertainty band
        # ----------------------------------------------------

        band.Draw("E2 SAME")

        # ----------------------------------------------------
        # Individual component fractions
        # ----------------------------------------------------

        component_projections = []
        component_fractions = []

        for label, h2, color in components2d:

            h_component = projection_x(
                h2,
                ibin,
                f"component_{label}_{ibin}_{os.path.basename(output)}",
            )

            fraction = make_component_fraction(
                h_component,
                h_mc,
                f"fraction_{label}_{ibin}_{os.path.basename(output)}",
                color,
            )

            fraction.Draw("HIST SAME")

            component_projections.append(
                h_component
            )

            component_fractions.append(
                fraction
            )

            drawn_component_labels.add(label)

        # ----------------------------------------------------
        # Residual category, if component sum is incomplete
        # ----------------------------------------------------

        h_residual = h_mc.Clone(
            f"residual_{ibin}_{os.path.basename(output)}"
        )
        h_residual.SetDirectory(0)

        for h_component in component_projections:
            h_residual.Add(h_component, -1.0)

        max_total = max(
            (
                abs(h_mc.GetBinContent(i))
                for i in range(1, h_mc.GetNbinsX() + 1)
            ),
            default=0.0,
        )

        max_residual = max(
            (
                abs(h_residual.GetBinContent(i))
                for i in range(1, h_residual.GetNbinsX() + 1)
            ),
            default=0.0,
        )

        # Relative diagnostic tolerance
        has_residual = (
            max_residual > 1e-5 * max(1.0, max_total)
        )

        if has_residual:
            print(
                f"[COMPONENT CLOSURE] Slice {ibin}: "
                f"max residual={max_residual:.6g}"
            )

            residual_fraction = make_component_fraction(
                h_residual,
                h_mc,
                f"residual_fraction_{ibin}_{os.path.basename(output)}",
                RESIDUAL_COLOR,
            )

            residual_fraction.SetLineStyle(2)
            residual_fraction.Draw("HIST SAME")

            keep.append(residual_fraction)
            residual_drawn = True

        # ----------------------------------------------------
        # Red unity reference
        # ----------------------------------------------------

        xmin = ratio.GetXaxis().GetXmin()
        xmax = ratio.GetXaxis().GetXmax()

        unity = ROOT.TLine(
            xmin, 1.0,
            xmax, 1.0,
        )

        unity.SetLineColor(ROOT.kRed + 1)
        unity.SetLineWidth(2)
        unity.Draw("SAME")

        # ----------------------------------------------------
        # Data / MC points
        # ----------------------------------------------------

        graph.Draw("P SAME")

        # ----------------------------------------------------
        # Slice label
        # ----------------------------------------------------

        low = slice_axis.GetBinLowEdge(ibin)
        high = slice_axis.GetBinUpEdge(ibin)

        label_text = (
            f"{low:.2f} < {slice_label} < {high:.2f}"
        )

        pad.cd()

        label = ROOT.TLatex(
            1.0 - pad.GetRightMargin() - 0.01,
            1.0 - pad.GetTopMargin() - 0.01,
            label_text,
        )

        label.SetNDC()
        label.SetTextFont(42)
        label.SetTextAlign(33)

        if nrows == 1:
            text_size = 0.03
        elif ncols < nrows:
            text_size = 28.0 / (150.0 * nrows)
        elif ncols == nrows:
            text_size = 10.0 / (150.0 * ncols)
        else:
            text_size = 18.0 / (150.0 * ncols)

        label.SetTextSize(text_size)
        label.Draw()

        pad.RedrawAxis()

        keep.extend([
            h_data,
            h_mc,
            ratio,
            graph,
            band,
            unity,
            label,
            h_residual,
        ])

        keep.extend(component_projections)
        keep.extend(component_fractions)

    # --------------------------------------------------------
    # Shared axes
    # --------------------------------------------------------

    gc.cd()

    gc.SetXTitle(horizontal_label)
    gc.SetYTitle("Data / MC and MC component fraction")
    gc.SetYLimits(ymin, ymax)
    gc.SetTitleSize(20.0)

    # ============================================================
    # LEGEND
    # ============================================================

    legend = ROOT.TLegend(0.35, 0.01, 0.88, 0.075)
    legend.SetNColumns(4)
    legend.SetBorderSize(0)
    legend.SetFillStyle(0)
    legend.SetTextFont(42)
    legend.SetTextSize(0.018)

    legend.AddEntry(graph, "Data / MC", "lep")
    legend.AddEntry(unity, "Total MC / MC", "l")
    legend.AddEntry(band, "MC statistical uncertainty", "f")

    for label, h2, color in components2d:
        dummy = ROOT.TLine(0, 0, 1, 0)
        dummy.SetLineColor(color)
        dummy.SetLineWidth(2)
        legend.AddEntry(dummy, label, "l")
        keep.append(dummy)

    if residual_drawn:
        residual_dummy = ROOT.TLine(0, 0, 1, 0)
        residual_dummy.SetLineColor(RESIDUAL_COLOR)
        residual_dummy.SetLineStyle(2)
        residual_dummy.SetLineWidth(2)
        legend.AddEntry(
            residual_dummy,
            "Unclassified residual",
            "l"
        )
        keep.append(residual_dummy)

    legend.Draw()
    keep.append(legend)

    gc.Modified()
    gc.Update()

    # --------------------------------------------------------
    # Save
    # --------------------------------------------------------

    gc.Print(output + ".png")
    gc.Print(output + ".pdf")

    print(f"Saved: {output}.png")
    print(f"Saved: {output}.pdf")

    # Print the component legend mapping.
    print("\n========== COMPONENT COLORS ==========")
    print("Black markers : Data / total MC")
    print("Red line      : Total MC / total MC = 1")

    for label, _, color in components2d:
        print(f"{label:20s}: ROOT color {color}")

    if residual_drawn:
        print("Unclassified residual: gray dashed")

    print("======================================\n")

    return gc, keep


